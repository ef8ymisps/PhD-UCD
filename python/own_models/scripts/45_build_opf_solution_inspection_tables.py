"""Build side-by-side OPF inspection tables by mathematical family.

This script implements the `opf-solution-inspection` discipline:

* one CSV per decision-variable family (`Pg`, `Qg`, `Vm`, `Va`, `Pf`, ...);
* one CSV per inequality-constraint family;
* rows sorted by the largest nonzero/material differences first;
* generator and branch constraint rows enriched with bus/from/to identifiers.

Default scope is the 1888_rte objective-gap scenarios discussed on
2026-07-21. The script reads the raw own-vs-PowerModels exports generated by
Julia/Python validation sweeps:

    results/own_vs_powermodels/{julia,julia_pm_like,python_pm_like}/...
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import json
import math

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
SOURCE_ROOT = ROOT / "results" / "own_vs_powermodels"
REFERENCE_ROOT = ROOT / "results" / "reference" / "powermodels" / "ac_opf"
OUT_ROOT = (
    SOURCE_ROOT
    / "_organized_for_meeting"
    / "10_opf_solution_inspection"
    / "1888_rte_objective_gap"
)
TOL = 1e-6
OBSOLETE_OUTPUT_NAMES = {"thermal_from.csv", "thermal_to.csv"}


def disk_path(path: Path) -> Path:
    if not path.is_absolute():
        path = path.resolve()
    if path.drive and not str(path).startswith("\\\\?\\"):
        return Path("\\\\?\\" + str(path))
    return path


def write_csv(df: pd.DataFrame, path: Path) -> None:
    disk_path(path.parent).mkdir(parents=True, exist_ok=True)
    df.to_csv(disk_path(path), index=False)


def remove_obsolete_outputs() -> None:
    if not OUT_ROOT.exists():
        return
    for path in OUT_ROOT.rglob("*"):
        if path.is_file() and path.name in OBSOLETE_OUTPUT_NAMES:
            disk_path(path).unlink()


@dataclass(frozen=True)
class ScenarioSpec:
    model_variant: str
    source_subdir: str
    case: str
    scenario: str


SCENARIOS = [
    ScenarioSpec("julia_current", "julia", "1888_rte", "load_x0.8"),
    ScenarioSpec("julia_current", "julia", "1888_rte", "load_x1.2_reactive_stress"),
    ScenarioSpec("julia_pm_like", "julia_pm_like", "1888_rte", "load_x0.8"),
    ScenarioSpec("julia_pm_like", "julia_pm_like", "1888_rte", "load_x1.2_reactive_stress"),
    ScenarioSpec("julia_pm_like", "julia_pm_like", "1888_rte", "qg_limits_x0.6"),
    ScenarioSpec("python_pm_like_zero", "python_pm_like", "1888_rte", "load_x0.8"),
    ScenarioSpec("python_pm_like_zero", "python_pm_like", "1888_rte", "load_x1.2_reactive_stress"),
]


def read_csv(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def blanked(value):
    if value is None:
        return ""
    if isinstance(value, float) and math.isnan(value):
        return ""
    return value


def diff(own, pm):
    try:
        return float(own) - float(pm)
    except (TypeError, ValueError):
        return math.nan


def flag_at(value, bound) -> bool:
    try:
        return abs(float(value) - float(bound)) <= TOL
    except (TypeError, ValueError):
        return False


def add_var_row(
    rows: list[dict],
    spec: ScenarioSpec,
    family: str,
    variable_name: str,
    element_type: str,
    element_id,
    own_value,
    pm_value,
    *,
    bus_id="",
    from_bus="",
    to_bus="",
    lower_bound=math.nan,
    upper_bound=math.nan,
) -> None:
    value_diff = diff(own_value, pm_value)
    rows.append(
        {
            "case": spec.case,
            "scenario": spec.scenario,
            "model_variant": spec.model_variant,
            "variable_family": family,
            "variable_name": variable_name,
            "element_type": element_type,
            "element_id": element_id,
            "bus_id": blanked(bus_id),
            "from_bus": blanked(from_bus),
            "to_bus": blanked(to_bus),
            "own_value": own_value,
            "powermodels_value": pm_value,
            "value_difference": value_diff,
            "abs_value_difference": abs(value_diff) if pd.notna(value_diff) else math.nan,
            "own_lower_bound": blanked(lower_bound),
            "own_upper_bound": blanked(upper_bound),
            "powermodels_lower_bound": blanked(lower_bound),
            "powermodels_upper_bound": blanked(upper_bound),
            "own_at_lower": flag_at(own_value, lower_bound),
            "powermodels_at_lower": flag_at(pm_value, lower_bound),
            "own_at_upper": flag_at(own_value, upper_bound),
            "powermodels_at_upper": flag_at(pm_value, upper_bound),
        }
    )


def binding_relation(own_binding: bool, pm_binding: bool) -> str:
    if own_binding and pm_binding:
        return "both_binding"
    if own_binding:
        return "only_own_binding"
    if pm_binding:
        return "only_pm_binding"
    return "neither_binding"


def add_ineq_row(
    rows: list[dict],
    spec: ScenarioSpec,
    family: str,
    constraint_type: str,
    element_type: str,
    element_id,
    own_value,
    pm_value,
    own_margin,
    pm_margin,
    own_binding,
    pm_binding,
    *,
    bus_id="",
    from_bus="",
    to_bus="",
) -> None:
    value_difference = diff(own_value, pm_value)
    margin_difference = diff(own_margin, pm_margin)
    own_violates = pd.notna(own_margin) and float(own_margin) < -TOL
    pm_violates = pd.notna(pm_margin) and float(pm_margin) < -TOL
    abs_margin = abs(margin_difference) if pd.notna(margin_difference) else math.nan
    rows.append(
        {
            "case": spec.case,
            "scenario": spec.scenario,
            "model_variant": spec.model_variant,
            "constraint_family": family,
            "constraint_type": constraint_type,
            "element_type": element_type,
            "element_id": element_id,
            "bus_id": blanked(bus_id),
            "from_bus": blanked(from_bus),
            "to_bus": blanked(to_bus),
            "own_value": own_value,
            "powermodels_value": pm_value,
            "value_difference": value_difference,
            "abs_value_difference": abs(value_difference) if pd.notna(value_difference) else math.nan,
            "own_margin": own_margin,
            "powermodels_margin": pm_margin,
            "margin_difference": margin_difference,
            "abs_margin_difference": abs_margin,
            "own_binding": bool(own_binding),
            "powermodels_binding": bool(pm_binding),
            "binding_relation": binding_relation(bool(own_binding), bool(pm_binding)),
            "tolerance_attributable": bool(pd.notna(abs_margin) and abs_margin <= TOL),
            "material_mismatch": bool((bool(own_binding) != bool(pm_binding)) and pd.notna(abs_margin) and abs_margin > TOL),
            "own_violates_limit": bool(own_violates),
            "powermodels_violates_limit": bool(pm_violates),
        }
    )


def scenario_dir(spec: ScenarioSpec) -> Path:
    return SOURCE_ROOT / spec.source_subdir / spec.case / spec.scenario


def reference_case_path(spec: ScenarioSpec) -> Path:
    return REFERENCE_ROOT / f"pglib_opf_case{spec.case}_{spec.scenario}_case.json"


def gen_bus_map(spec: ScenarioSpec) -> dict[str, int]:
    path = reference_case_path(spec)
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    return {str(gen_id): int(gen.get("gen_bus", "")) for gen_id, gen in data.get("gen", {}).items()}


def collect_scenario(spec: ScenarioSpec):
    base = scenario_dir(spec)
    gens = read_csv(base / "generators.csv")
    buses = read_csv(base / "buses.csv")
    branches = read_csv(base / "branches.csv")
    if gens is None or buses is None or branches is None:
        missing = [
            str(base / name)
            for name, df in (
                ("generators.csv", gens),
                ("buses.csv", buses),
                ("branches.csv", branches),
            )
            if df is None
        ]
        raise FileNotFoundError("Missing raw export(s): " + "; ".join(missing))
    if "bus_id" not in gens.columns:
        mapping = gen_bus_map(spec)
        gens = gens.copy()
        gens["bus_id"] = gens["gen_id"].astype(str).map(mapping)
    return gens, buses, branches


def build_tables():
    var_rows: dict[str, list[dict]] = {k: [] for k in ("pg", "qg", "vm", "va", "pf", "qf", "pt", "qt")}
    ineq_rows: dict[str, list[dict]] = {
        "pg_bounds": [],
        "qg_bounds": [],
        "vm_bounds": [],
        "thermal": [],
        "angle_difference": [],
    }
    manifest = []

    for spec in SCENARIOS:
        try:
            gens, buses, branches = collect_scenario(spec)
        except FileNotFoundError as exc:
            manifest.append({**spec.__dict__, "status": "missing_raw_exports", "note": str(exc)})
            continue
        manifest.append({**spec.__dict__, "status": "included", "note": str(scenario_dir(spec))})

        for _, r in gens.iterrows():
            add_var_row(var_rows["pg"], spec, "Pg", "Pg", "generator", r["gen_id"], r["own_pg"], r["pm_pg"], bus_id=r["bus_id"], lower_bound=r["pmin"], upper_bound=r["pmax"])
            add_var_row(var_rows["qg"], spec, "Qg", "Qg", "generator", r["gen_id"], r["own_qg"], r["pm_qg"], bus_id=r["bus_id"], lower_bound=r["qmin"], upper_bound=r["qmax"])
            add_ineq_row(ineq_rows["pg_bounds"], spec, "Pg bounds", "pg_min", "generator", r["gen_id"], r["own_pg"], r["pm_pg"], r["own_pg"] - r["pmin"], r["pm_pg"] - r["pmin"], r["own_at_pmin"], r["pm_at_pmin"], bus_id=r["bus_id"])
            add_ineq_row(ineq_rows["pg_bounds"], spec, "Pg bounds", "pg_max", "generator", r["gen_id"], r["own_pg"], r["pm_pg"], r["pmax"] - r["own_pg"], r["pmax"] - r["pm_pg"], r["own_at_pmax"], r["pm_at_pmax"], bus_id=r["bus_id"])
            add_ineq_row(ineq_rows["qg_bounds"], spec, "Qg bounds", "qg_min", "generator", r["gen_id"], r["own_qg"], r["pm_qg"], r["own_qg"] - r["qmin"], r["pm_qg"] - r["qmin"], r["own_at_qmin"], r["pm_at_qmin"], bus_id=r["bus_id"])
            add_ineq_row(ineq_rows["qg_bounds"], spec, "Qg bounds", "qg_max", "generator", r["gen_id"], r["own_qg"], r["pm_qg"], r["qmax"] - r["own_qg"], r["qmax"] - r["pm_qg"], r["own_at_qmax"], r["pm_at_qmax"], bus_id=r["bus_id"])

        for _, r in buses.iterrows():
            add_var_row(var_rows["vm"], spec, "Vm", "Vm", "bus", r["bus_id"], r["own_vm"], r["pm_vm"], bus_id=r["bus_id"], lower_bound=r["vmin"], upper_bound=r["vmax"])
            add_var_row(var_rows["va"], spec, "Va", "Va", "bus", r["bus_id"], r["own_va"], r["pm_va"], bus_id=r["bus_id"])
            add_ineq_row(ineq_rows["vm_bounds"], spec, "Vm bounds", "vm_min", "bus", r["bus_id"], r["own_vm"], r["pm_vm"], r["own_vm"] - r["vmin"], r["pm_vm"] - r["vmin"], r["own_at_vmin"], r["pm_at_vmin"], bus_id=r["bus_id"])
            add_ineq_row(ineq_rows["vm_bounds"], spec, "Vm bounds", "vm_max", "bus", r["bus_id"], r["own_vm"], r["pm_vm"], r["vmax"] - r["own_vm"], r["vmax"] - r["pm_vm"], r["own_at_vmax"], r["pm_at_vmax"], bus_id=r["bus_id"])

        for _, r in branches.iterrows():
            from_bus = r.get("from_bus", "")
            to_bus = r.get("to_bus", "")
            for key, label in (("pf", "Pf"), ("qf", "Qf"), ("pt", "Pt"), ("qt", "Qt")):
                own_col = f"own_{key}"
                pm_col = f"pm_{key}"
                if own_col in branches.columns and pm_col in branches.columns:
                    add_var_row(var_rows[key], spec, label, label, "branch", r["branch_id"], r[own_col], r[pm_col], from_bus=from_bus, to_bus=to_bus)

            own_sf = r.get("own_sf", r.get("own_loading_abs", math.nan))
            pm_sf = r.get("pm_sf", r.get("pm_loading_abs", math.nan))
            own_st = r.get("own_st", math.nan)
            pm_st = r.get("pm_st", math.nan)
            rate = r.get("rate_a", math.nan)
            own_from_binding = r.get("own_from_binding", r.get("own_binding", False))
            pm_from_binding = r.get("pm_from_binding", r.get("pm_binding", False))
            own_to_binding = r.get("own_to_binding", r.get("own_binding", False))
            pm_to_binding = r.get("pm_to_binding", r.get("pm_binding", False))
            add_ineq_row(ineq_rows["thermal"], spec, "Thermal", "thermal_from", "branch", r["branch_id"], own_sf, pm_sf, rate - own_sf, rate - pm_sf, own_from_binding, pm_from_binding, from_bus=from_bus, to_bus=to_bus)
            if pd.notna(own_st) and pd.notna(pm_st):
                add_ineq_row(ineq_rows["thermal"], spec, "Thermal", "thermal_to", "branch", r["branch_id"], own_st, pm_st, rate - own_st, rate - pm_st, own_to_binding, pm_to_binding, from_bus=from_bus, to_bus=to_bus)

            if "own_angle_diff" in branches.columns and "pm_angle_diff" in branches.columns:
                add_ineq_row(ineq_rows["angle_difference"], spec, "Angle difference", "angle_lower", "branch", r["branch_id"], r["own_angle_diff"], r["pm_angle_diff"], r["own_angle_diff"] - r["angmin"], r["pm_angle_diff"] - r["angmin"], r["own_angle_lower_binding"], r["pm_angle_lower_binding"], from_bus=from_bus, to_bus=to_bus)
                add_ineq_row(ineq_rows["angle_difference"], spec, "Angle difference", "angle_upper", "branch", r["branch_id"], r["own_angle_diff"], r["pm_angle_diff"], r["angmax"] - r["own_angle_diff"], r["angmax"] - r["pm_angle_diff"], r["own_angle_upper_binding"], r["pm_angle_upper_binding"], from_bus=from_bus, to_bus=to_bus)

    return var_rows, ineq_rows, pd.DataFrame(manifest)


def write_sorted(df: pd.DataFrame, path: Path, *, variable: bool) -> None:
    if df.empty:
        write_csv(df, path)
        return
    if variable:
        df = df.sort_values(["abs_value_difference"], ascending=[False])
    else:
        df = df.sort_values(["material_mismatch", "abs_margin_difference"], ascending=[False, False])
    write_csv(df, path)


def simplified_variable_table(df: pd.DataFrame, family: str, *, aggregate: bool) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame()

    prefix = ["model_variant", "case", "scenario"] if aggregate else []
    value_cols = ["own_value", "powermodels_value", "value_difference"]
    names = {
        "own_value": f"own_{family}",
        "powermodels_value": f"pm_{family}",
        "value_difference": f"{family}_diff",
    }

    if family in ("pg", "qg"):
        cols = prefix + ["element_id", "bus_id"] + value_cols
        names["element_id"] = "gen_id"
    elif family in ("vm", "va"):
        cols = prefix + ["bus_id"] + value_cols
    else:
        cols = prefix + ["element_id", "from_bus", "to_bus"] + value_cols
        names["element_id"] = "branch_id"

    cols = [c for c in cols if c in df.columns]
    return df[cols].rename(columns=names)


def simplified_inequality_table(df: pd.DataFrame, family: str, *, aggregate: bool) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame()

    prefix = ["model_variant", "case", "scenario"] if aggregate else []
    common = [
        "constraint_type",
        "own_value",
        "powermodels_value",
        "value_difference",
        "own_margin",
        "powermodels_margin",
        "margin_difference",
        "binding_relation",
        "material_mismatch",
        "own_violates_limit",
        "powermodels_violates_limit",
    ]
    names = {
        "powermodels_value": "pm_value",
        "powermodels_margin": "pm_margin",
        "powermodels_violates_limit": "pm_violates_limit",
    }

    if family in ("pg_bounds", "qg_bounds"):
        cols = prefix + ["constraint_type", "element_id", "bus_id"] + common[1:]
        names["element_id"] = "gen_id"
    elif family == "vm_bounds":
        cols = prefix + ["constraint_type", "bus_id"] + common[1:]
    else:
        cols = prefix + ["constraint_type", "element_id", "from_bus", "to_bus"] + common[1:]
        names["element_id"] = "branch_id"

    cols = [c for c in cols if c in df.columns]
    out = df[cols].rename(columns=names)
    if family == "thermal" and "constraint_type" in out.columns:
        out.insert(
            out.columns.get_loc("constraint_type") + 1,
            "side",
            out["constraint_type"].map({"thermal_from": "from", "thermal_to": "to"}).fillna(""),
        )
    return out


def write_variable_table(df: pd.DataFrame, family: str, path: Path, *, aggregate: bool) -> None:
    if not df.empty:
        df = df.sort_values(["abs_value_difference"], ascending=[False])
    write_csv(simplified_variable_table(df, family, aggregate=aggregate), path)


def write_inequality_table(df: pd.DataFrame, family: str, path: Path, *, aggregate: bool) -> None:
    if not df.empty:
        df = df.sort_values(["material_mismatch", "abs_margin_difference"], ascending=[False, False])
    write_csv(simplified_inequality_table(df, family, aggregate=aggregate), path)


def scenario_subset(df: pd.DataFrame, model_variant: str, case: str, scenario: str) -> pd.DataFrame:
    if df.empty:
        return df.copy()
    return df[
        (df["model_variant"] == model_variant)
        & (df["case"] == case)
        & (df["scenario"] == scenario)
    ].copy()


def summarize_variables(var_rows: dict[str, list[dict]]) -> pd.DataFrame:
    rows = []
    for name, records in var_rows.items():
        df = pd.DataFrame(records)
        if df.empty:
            continue
        grouped = df.groupby(["model_variant", "case", "scenario", "variable_family"], dropna=False)
        for keys, g in grouped:
            rows.append(
                {
                    "model_variant": keys[0],
                    "case": keys[1],
                    "scenario": keys[2],
                    "variable_family": keys[3],
                    "n_rows": len(g),
                    "n_nonzero_gt_1e_minus_6": int((g["abs_value_difference"] > TOL).sum()),
                    "max_abs_value_difference": g["abs_value_difference"].max(),
                    "mean_abs_value_difference": g["abs_value_difference"].mean(),
                }
            )
    if not rows:
        return pd.DataFrame(
            columns=[
                "model_variant",
                "case",
                "scenario",
                "variable_family",
                "n_rows",
                "n_nonzero_gt_1e_minus_6",
                "max_abs_value_difference",
                "mean_abs_value_difference",
            ]
        )
    return pd.DataFrame(rows).sort_values(["model_variant", "scenario", "variable_family"])


def summarize_inequalities(ineq_rows: dict[str, list[dict]]) -> pd.DataFrame:
    rows = []
    for name, records in ineq_rows.items():
        df = pd.DataFrame(records)
        if df.empty:
            continue
        grouped = df.groupby(["model_variant", "case", "scenario", "constraint_family"], dropna=False)
        for keys, g in grouped:
            rows.append(
                {
                    "model_variant": keys[0],
                    "case": keys[1],
                    "scenario": keys[2],
                    "constraint_family": keys[3],
                    "n_rows": len(g),
                    "n_binding_mismatches": int((g["binding_relation"].isin(["only_own_binding", "only_pm_binding"])).sum()),
                    "n_material_mismatches": int(g["material_mismatch"].sum()),
                    "n_own_violations": int(g["own_violates_limit"].sum()),
                    "n_powermodels_violations": int(g["powermodels_violates_limit"].sum()),
                    "max_abs_margin_difference": g["abs_margin_difference"].max(),
                }
            )
    if not rows:
        return pd.DataFrame(
            columns=[
                "model_variant",
                "case",
                "scenario",
                "constraint_family",
                "n_rows",
                "n_binding_mismatches",
                "n_material_mismatches",
                "n_own_violations",
                "n_powermodels_violations",
                "max_abs_margin_difference",
            ]
        )
    return pd.DataFrame(rows).sort_values(["model_variant", "scenario", "constraint_family"])


def main() -> None:
    remove_obsolete_outputs()
    disk_path(OUT_ROOT).mkdir(parents=True, exist_ok=True)

    var_rows, ineq_rows, manifest = build_tables()
    variable_tables = {family: pd.DataFrame(rows) for family, rows in var_rows.items()}
    inequality_tables = {family: pd.DataFrame(rows) for family, rows in ineq_rows.items()}

    for family, rows in var_rows.items():
        write_variable_table(pd.DataFrame(rows), family, OUT_ROOT / f"{family}.csv", aggregate=True)
    for family, rows in ineq_rows.items():
        write_inequality_table(pd.DataFrame(rows), family, OUT_ROOT / f"{family}.csv", aggregate=True)

    variable_summary = summarize_variables(var_rows)
    inequality_summary = summarize_inequalities(ineq_rows)
    write_csv(variable_summary, OUT_ROOT / "variable_summary_by_family.csv")
    write_csv(inequality_summary, OUT_ROOT / "constraint_summary_by_family.csv")
    write_csv(manifest, OUT_ROOT / "inspection_manifest.csv")

    index_rows = []
    included = manifest[manifest["status"] == "included"].copy()
    for _, row in included.iterrows():
        model_variant = row["model_variant"]
        case = row["case"]
        scenario = row["scenario"]
        scenario_out = OUT_ROOT / "by_model_scenario" / model_variant / scenario
        disk_path(scenario_out).mkdir(parents=True, exist_ok=True)

        for family, df in variable_tables.items():
            write_variable_table(
                scenario_subset(df, model_variant, case, scenario),
                family,
                scenario_out / f"{family}.csv",
                aggregate=False,
            )
        for family, df in inequality_tables.items():
            write_inequality_table(
                scenario_subset(df, model_variant, case, scenario),
                family,
                scenario_out / f"{family}.csv",
                aggregate=False,
            )

        write_csv(
            scenario_subset(variable_summary, model_variant, case, scenario).drop(
                columns=["model_variant", "case", "scenario"],
                errors="ignore",
            ),
            scenario_out / "variable_summary_by_family.csv",
        )
        write_csv(
            scenario_subset(inequality_summary, model_variant, case, scenario).drop(
                columns=["model_variant", "case", "scenario"],
                errors="ignore",
            ),
            scenario_out / "constraint_summary_by_family.csv",
        )
        write_csv(pd.DataFrame([row.to_dict()]), scenario_out / "inspection_manifest.csv")
        index_rows.append(
            {
                "model_variant": model_variant,
                "case": case,
                "scenario": scenario,
                "folder": str(scenario_out),
            }
        )

    write_csv(pd.DataFrame(index_rows), OUT_ROOT / "by_model_scenario_index.csv")
    print(f"Wrote OPF solution inspection tables to {OUT_ROOT}")


if __name__ == "__main__":
    main()
